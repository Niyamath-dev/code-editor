// Load saved project
function loadSavedProject() {
    try {
        const savedProject = localStorage.getItem('hcj_editor_saved_project');
        if (savedProject) {
            const projectData = JSON.parse(savedProject);
            
            if (confirm("Load your previously saved project? This will replace current content.")) {
                // Load the saved project data
                if (projectData.html !== undefined) {
                    document.getElementById("htmlMobile").value = projectData.html;
                }
                if (projectData.css !== undefined) {
                    document.getElementById("cssMobile").value = projectData.css;
                }
                if (projectData.js !== undefined) {
                    document.getElementById("jsMobile").value = projectData.js;
                }
                
                // Update line numbers and preview
                if (typeof HCJEditor !== "undefined") {
                    ['html', 'css', 'js'].forEach(type => {
                        HCJEditor.updateLineNumbers(type);
                    });
                    HCJEditor.updatePreview();
                    HCJEditor.showNotification("Saved project loaded successfully!", "success");
                }
            }
        } else {
            if (typeof HCJEditor !== "undefined") {
                HCJEditor.showNotification("No saved project found.", "info");
            } else {
                alert("No saved project found.");
            }
        }
    } catch (error) {
        console.error('Error loading saved project:', error);
        if (typeof HCJEditor !== "undefined") {
            HCJEditor.showNotification("Failed to load saved project.", "error");
        } else {
            alert("Failed to load saved project.");
        }
    }
}

