// Copy to clipboard function
function copyToClipboard(text, message) {
    navigator.clipboard.writeText(text).then(function() {
        if (typeof HCJEditor !== "undefined") {
            HCJEditor.showNotification(message || "Copied to clipboard!", "success");
        } else {
            alert(message || "Copied to clipboard!");
        }
    }).catch(function(err) {
        console.error('Could not copy text: ', err);
        if (typeof HCJEditor !== "undefined") {
            HCJEditor.showNotification("Failed to copy to clipboard", "error");
        } else {
            alert("Failed to copy to clipboard");
        }
    });
}

// Download file function
function downloadFile(content, filename, mimeType) {
    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    
    if (typeof HCJEditor !== "undefined") {
        HCJEditor.showNotification("File downloaded: " + filename, "success");
    }
}
