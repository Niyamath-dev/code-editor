// Enhanced save project functionality
function saveProject() {
    const html = document.getElementById("htmlMobile").value;
    const css = document.getElementById("cssMobile").value;
    const js = document.getElementById("jsMobile").value;
    
    if (!html.trim() && !css.trim() && !js.trim()) {
        if (typeof HCJEditor !== "undefined") {
            HCJEditor.showNotification("No content to save. Please add some code first.", "warning");
        } else {
            alert("No content to save. Please add some code first.");
        }
        return;
    }
    
    // Create project data
    const projectData = {
        html: html,
        css: css,
        js: js,
        timestamp: new Date().toISOString(),
        title: "My HCJ Project"
    };
    
    try {
        // Save to localStorage
        localStorage.setItem('hcj_editor_saved_project', JSON.stringify(projectData));
        
        // Also update the auto-save
        localStorage.setItem('hcj_editor_autosave', JSON.stringify(projectData));
        
        // Update HCJEditor state if available
        if (typeof HCJEditor !== "undefined") {
            HCJEditor.state.hasUnsavedChanges = false;
            HCJEditor.state.lastSaved = new Date();
            HCJEditor.hideUnsavedIndicator();
            HCJEditor.showNotification("Project saved successfully!", "success");
        } else {
            alert("Project saved successfully!");
        }
        
        console.log('Project saved to localStorage');
    } catch (error) {
        console.error('Save error:', error);
        if (typeof HCJEditor !== "undefined") {
            HCJEditor.showNotification("Failed to save project. Storage might be full.", "error");
        } else {
            alert("Failed to save project. Storage might be full.");
        }
    }
}

