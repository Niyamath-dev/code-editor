// Clear editor function
function clearEditor(type) {
    const editor = document.getElementById(type + "Mobile");
    const lineNumbers = document.getElementById("lineCounter" + type.charAt(0).toUpperCase() + type.slice(1) + "Mobi");
    
    if (confirm("Are you sure you want to clear all " + type.toUpperCase() + " code?")) {
        editor.value = "";
        lineNumbers.value = "1.";
        editor.dispatchEvent(new Event("input"));
        if (typeof HCJEditor !== "undefined") {
            HCJEditor.showNotification(type.toUpperCase() + " editor cleared", "info");
        }
    }
}

// Download complete project
function downloadCompleteProject() {
    // Use the DownloadManager if available, otherwise fallback to basic implementation
    if (typeof DownloadManager !== "undefined") {
        DownloadManager.downloadProject('combined');
        return;
    }
    
    // Fallback implementation
    const html = document.getElementById("htmlMobile").value;
    const css = document.getElementById("cssMobile").value;
    const js = document.getElementById("jsMobile").value;
    
    if (!html.trim() && !css.trim() && !js.trim()) {
        if (typeof HCJEditor !== "undefined") {
            HCJEditor.showNotification("No content to download", "warning");
        } else {
            alert("No content to download");
        }
        return;
    }
    
    // Create a complete HTML file with embedded CSS and JS
    const timestamp = new Date().toISOString();
    const completeHTML = `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>My Project</title>
    <!-- Generated by HCJ Code Editor on ${timestamp} -->
    ${css.trim() ? `<style>\n${css}\n    </style>` : ''}
</head>
<body>
${html}
${js.trim() ? `    <script>\n${js}\n    </script>` : ''}
</body>
</html>`;
    
    // Create download
    const blob = new Blob([completeHTML], { type: 'text/html' });
    const url = window.URL.createObjectURL(blob);
    const link = document.createElement('a');
    
    link.href = url;
    link.download = `my-project-${new Date().toISOString().slice(0, 19).replace(/[:.]/g, '-')}.html`;
    link.style.display = 'none';
    
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    
    // Clean up
    setTimeout(() => {
        window.URL.revokeObjectURL(url);
    }, 100);
    
    if (typeof HCJEditor !== "undefined") {
        HCJEditor.showNotification("Project downloaded successfully!", "success");
    } else {
        alert("Project downloaded successfully!");
    }
}

